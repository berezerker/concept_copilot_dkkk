def semantics_text(session):
    from ..workbook import semantics as sm
    sem = getattr(session, "sem", None)
    if not sem:
        return "не построен"
    su = sm.summary(sem)
    rows = sem["rows"]
    lines = [f"Отрасль: {su['industry_name']}. Описания строк: {'LLM (' + su['llm']['model'] + ')' if su.get('llm') else 'по правилам'}."]
    for f in su["factors"]:
        ex = [p["name"] for p in sorted(rows.values(), key=lambda p: -p["fanout"])
              if p["factor"] == f["id"] and p["kind"] in ("input", "mixed")][:3]
        lines.append(f"• {f['id']} — {f['name']} ({f['rows']} строк): " + "; ".join(x[:45] for x in ex))
    if su["subfactors"]:
        lines.append("Подфакторы: " + "; ".join(f"{x['id']} — {x['name']} ({x['rows']})" for x in su["subfactors"]))
    return "\n".join(lines)


def system_prompt(session):
    return SYSTEM.format(card=card_text(session.card), forecast_start=session.forecast_start,
                         semantics=semantics_text(session))
